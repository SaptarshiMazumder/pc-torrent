@runtime_checkable
class IStorageClient(Protocol):
    def upload_file(self, key: str, data: bytes, content_type: str = ...) -> None: ...
    def download_file(self, key: str) -> bytes: ...
    def file_exists(self, key: str) -> bool: ...
    def get_file_size(self, key: str) -> int | None: ...
    def delete_file(self, key: str) -> None: ...
    def list_files(self, prefix: str) -> list[str]: ...
    def generate_presigned_url(self, key: str, expires_in: int = ..., download_name: str | None = ...) -> str: ...
    def generate_presigned_upload_url(self, key: str, content_type: str = ..., expires_in: int = ...) -> str: ...
    def create_multipart_upload(self, key: str, content_type: str = ...) -> str: ...
    def generate_presigned_upload_part_url(self, key: str, upload_id: str, part_number: int, expires_in: int = ...) -> str: ...
    def complete_multipart_upload(self, key: str, upload_id: str, parts: list[dict]) -> dict: ...
    def abort_multipart_upload(self, key: str, upload_id: str) -> None: ...


